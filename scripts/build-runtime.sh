#!/bin/sh
# SPDX-License-Identifier: MPL-2.0
# Build the toolchain's target runtime, which NBT modules and guests link
# statically: picolibc (C library), compiler-rt builtins with emulated TLS
# (compiler helpers) and libc++, libc++abi and libunwind (C++). No QNX file is
# used.
#
#   scripts/build-runtime.sh <llvm-bin> <build-dir> <out-dir>
#
# <out-dir>/include gets the NBT C library headers (libc/include), which the
# SDK's module runtime implements. <out-dir>/aligned (strict alignment, the
# default) and <out-dir>/unaligned (unaligned accesses allowed: faster, but
# faulting on boards with strict alignment such as the QEMU VM) each hold a
# runtime and the target.mk its users must compile with. Needs CMake, Ninja
# and Meson (scripts/linux-run.sh has them).
set -eu
ROOT=$(cd "$(dirname "$0")/.." && pwd)
usage="usage: build-runtime.sh <llvm-bin> <build-dir> <out-dir>"
LLVM_BIN=$(cd "${1:?$usage}" && pwd)
mkdir -p "${2:?$usage}" "${3:?$usage}"
WORK=$(cd "$2" && pwd)
OUT=$(cd "$3" && pwd)
SRC=$ROOT/third_party/llvm-project

# The target. ARMv7-A, soft-float calling convention with VFPv3-D16, ARM state
# (QNX 6.5 kernels mishandle a thread's first FPU instruction in Thumb
# state), int-size enums.
TRIPLE=armv7a-none-eabi
ARCH="-marm -march=armv7-a -mfpu=vfpv3-d16 -mfloat-abi=softfp -fno-short-enums"
CODEGEN="-fPIC -femulated-tls"
# picolibc announces neither the clocks the module runtime provides nor POSIX
# under -std=c++NN.
DEFS="-D_POSIX_MONOTONIC_CLOCK=200112L -D_POSIX_TIMERS=200112L -D_DEFAULT_SOURCE"

rm -rf "$OUT/include"
cp -R "$ROOT/libc/include" "$OUT/include"

# variant <name> <alignment flag>
variant() {
    V=$OUT/$1
    W=$WORK/$1
    rm -rf "$V" "$W"
    mkdir -p "$V" "$W"
    # Source paths (compiler-rt's aborts name their file) relative to the
    # checkout, so the runtime is the same wherever it is built.
    FLAGS="$ARCH $2 -fPIC -ffunction-sections -fdata-sections -ffile-prefix-map=$ROOT/="
    LIBC_INC="-nostdlibinc -isystem $OUT/include -isystem $V/picolibc/include"

    cat > "$V/target.mk" <<EOF
# Generated by scripts/build-runtime.sh: what this runtime was compiled with.
# Code linked with it must use the same target and code generation flags.
NBT_TARGET_ARCH := --target=$TRIPLE $ARCH $2
NBT_TARGET_CODEGEN := $CODEGEN
NBT_TARGET_DEFS := $DEFS
EOF

    # --- picolibc ---
    cat > "$W/cross.txt" <<EOF
[binaries]
c = ['$LLVM_BIN/clang', '--target=$TRIPLE', '-nostdlib']
c_ld = '$LLVM_BIN/ld.lld'
ar = '$LLVM_BIN/llvm-ar'
nm = '$LLVM_BIN/llvm-nm'
strip = '$LLVM_BIN/llvm-strip'

[host_machine]
system = 'none'
cpu_family = 'arm'
cpu = 'armv7a'
endian = 'little'

[built-in options]
c_args = [$(printf "'%s', " $FLAGS)'-femulated-tls']

[properties]
skip_sanity_check = true
libgcc = '-lclang_rt.builtins'
EOF
    meson setup "$W/picolibc" "$ROOT/third_party/picolibc" --cross-file "$W/cross.txt" \
        --prefix "$V/picolibc" --libdir lib --includedir include \
        -Dbuildtype=release -Doptimization=2 \
        -Dmultilib=false -Dpicocrt=false -Dpicolib=false -Dsemihost=false \
        -Dtests=false -Dspecsdir=none \
        -Dthread-local-storage=true -Dsingle-thread=false \
        -Dposix-console=true -Dio-long-long=true -Dformat-default=double \
        -Derrno-function=false -Dnewlib-global-errno=false
    meson compile -C "$W/picolibc"
    meson install -C "$W/picolibc" --quiet

    CMAKE_TOOLS="-DCMAKE_C_COMPILER=$LLVM_BIN/clang -DCMAKE_CXX_COMPILER=$LLVM_BIN/clang++
        -DCMAKE_ASM_COMPILER=$LLVM_BIN/clang -DCMAKE_AR=$LLVM_BIN/llvm-ar -DCMAKE_NM=$LLVM_BIN/llvm-nm
        -DCMAKE_RANLIB=$LLVM_BIN/llvm-ranlib -DCMAKE_BUILD_TYPE=Release -DCMAKE_SYSTEM_NAME=Generic
        -DCMAKE_SYSTEM_PROCESSOR=arm -DCMAKE_TRY_COMPILE_TARGET_TYPE=STATIC_LIBRARY"

    # --- compiler-rt builtins, plus emulated TLS over the NBT pthread keys ---
    # (a bare-metal build leaves emutls out; hosted targets have it). The
    # builtins know the architecture as "armv7", not "armv7a".
    # shellcheck disable=SC2086
    cmake -S "$SRC/compiler-rt/lib/builtins" -B "$W/builtins" -G Ninja $CMAKE_TOOLS \
        -DCMAKE_C_COMPILER_TARGET=armv7-none-eabi -DCMAKE_ASM_COMPILER_TARGET=armv7-none-eabi \
        -DCMAKE_C_FLAGS="$FLAGS" -DCMAKE_ASM_FLAGS="$FLAGS" \
        -DCOMPILER_RT_BAREMETAL_BUILD=ON -DCOMPILER_RT_DEFAULT_TARGET_ONLY=ON \
        -DCOMPILER_RT_OS_DIR=. -DLLVM_ENABLE_PER_TARGET_RUNTIME_DIR=OFF
    cmake --build "$W/builtins"
    mkdir -p "$V/builtins"
    find "$W/builtins" -name 'libclang_rt.builtins*.a' -exec cp {} "$V/builtins/libclang_rt.builtins.a" \;
    # shellcheck disable=SC2086
    "$LLVM_BIN/clang" --target=$TRIPLE $FLAGS $DEFS $LIBC_INC -O2 -std=gnu11 -fvisibility=hidden -I"$SRC/compiler-rt/lib/builtins" \
        -c "$SRC/compiler-rt/lib/builtins/emutls.c" -o "$W/emutls.o"
    "$LLVM_BIN/llvm-ar" rs "$V/builtins/libclang_rt.builtins.a" "$W/emutls.o"
    # A bare-metal __clear_cache aborts: the module runtime has the real one
    # (the host's instruction cache flush), so code linked without it fails to
    # link instead of aborting when it first flushes.
    "$LLVM_BIN/llvm-ar" d "$V/builtins/libclang_rt.builtins.a" clear_cache.c.obj

    # --- libc++, libc++abi, libunwind ---
    # Static, over picolibc (which libc++ treats as newlib) and the NBT
    # pthread.h. Exceptions use ARM EHABI tables found through the linker's
    # __exidx_start/__exidx_end (bare-metal libunwind), so they never leave the
    # module. libc++abi is built for a hosted system instead: its bare-metal
    # variant jumps through an absolute address (a text relocation in a module)
    # and reads typeinfo as PC-relative; the hosted one reads it through the
    # GOT, which is why modules and guests link with --target2=got-rel.
    # pthread and clocks come from the C library: no "pthread"/"rt" library
    # for objects to name (LLD would look for them).
    CXX_FLAGS="$FLAGS -femulated-tls $LIBC_INC $DEFS -Dalloca=__builtin_alloca"
    # shellcheck disable=SC2086
    cmake -S "$SRC/runtimes" -B "$W/cxx" -G Ninja $CMAKE_TOOLS \
        -DLLVM_ENABLE_RUNTIMES="libcxx;libcxxabi;libunwind" \
        -DCMAKE_C_COMPILER_TARGET=$TRIPLE -DCMAKE_CXX_COMPILER_TARGET=$TRIPLE -DCMAKE_ASM_COMPILER_TARGET=$TRIPLE \
        -DCMAKE_C_FLAGS="$CXX_FLAGS" -DCMAKE_CXX_FLAGS="$CXX_FLAGS" -DCMAKE_ASM_FLAGS="$FLAGS" \
        -DCMAKE_POSITION_INDEPENDENT_CODE=ON -DCMAKE_INSTALL_PREFIX="$V/cxx" \
        -DLLVM_INCLUDE_TESTS=OFF -DLLVM_INCLUDE_DOCS=OFF \
        -DLIBCXX_ENABLE_SHARED=OFF -DLIBCXXABI_ENABLE_SHARED=OFF -DLIBUNWIND_ENABLE_SHARED=OFF \
        -DLIBCXX_CXX_ABI=libcxxabi -DLIBCXX_ENABLE_STATIC_ABI_LIBRARY=ON \
        -DLIBCXXABI_USE_LLVM_UNWINDER=ON -DLIBCXXABI_ENABLE_STATIC_UNWINDER=ON \
        -DLIBCXXABI_BAREMETAL=OFF -DLIBUNWIND_IS_BAREMETAL=ON \
        -DLIBCXX_HAS_PTHREAD_LIB=OFF -DLIBCXX_HAS_RT_LIB=OFF -DLIBCXXABI_HAS_PTHREAD_LIB=OFF \
        -DLIBCXX_ENABLE_THREADS=ON -DLIBCXX_HAS_PTHREAD_API=ON \
        -DLIBCXXABI_ENABLE_THREADS=ON -DLIBCXXABI_HAS_PTHREAD_API=ON \
        -DLIBUNWIND_ENABLE_THREADS=OFF -DLIBCXXABI_HAS_CXA_THREAD_ATEXIT_IMPL=OFF \
        -DLIBCXX_ENABLE_EXCEPTIONS=ON -DLIBCXXABI_ENABLE_EXCEPTIONS=ON -DLIBCXX_ENABLE_RTTI=ON \
        -DLIBCXX_ENABLE_FILESYSTEM=ON -DLIBCXX_ENABLE_RANDOM_DEVICE=OFF \
        -DLIBCXX_ENABLE_LOCALIZATION=ON -DLIBCXX_ENABLE_WIDE_CHARACTERS=ON \
        -DLIBCXX_ENABLE_MONOTONIC_CLOCK=ON \
        -DLIBCXX_USE_COMPILER_RT=ON -DLIBCXXABI_USE_COMPILER_RT=ON -DLIBUNWIND_USE_COMPILER_RT=ON \
        -DLIBCXX_INCLUDE_TESTS=OFF -DLIBCXX_INCLUDE_BENCHMARKS=OFF -DLIBCXXABI_INCLUDE_TESTS=OFF \
        -DLIBUNWIND_INCLUDE_TESTS=OFF -DLIBCXX_INCLUDE_DOCS=OFF -DLIBUNWIND_INCLUDE_DOCS=OFF
    cmake --build "$W/cxx"
    cmake --install "$W/cxx"
}

variant aligned -mno-unaligned-access
variant unaligned -munaligned-access
echo "runtime: $OUT"
